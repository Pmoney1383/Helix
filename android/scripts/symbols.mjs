// Downloads Material Symbols Rounded (24px, weight 400) as SVG path data and writes Kotlin. Usage: node symbols.mjs <out.kt>
import fs from "node:fs";
const names = {
  // Kotlin name: [material symbol, fill variants wanted]
  Home: ["home", true], Chat: ["chat_bubble", true], Call: ["call", true], Settings: ["settings", true],
  BarChart: ["bar_chart", false], VerifiedUser: ["verified_user", false], ChevronRight: ["chevron_right", false],
  MoreHoriz: ["more_horiz", false], VisibilityOff: ["visibility_off", false],
  Schedule: ["schedule", false], DesktopWindows: ["desktop_windows", false], Forum: ["forum", false],
  AddCircle: ["add_circle", true], ForkRight: ["fork_right", false], NotificationsActive: ["notifications_active", false],
  Warning: ["warning", true], ArrowUpward: ["arrow_upward", false], CallEnd: ["call_end", true],
  CallReceived: ["call_received", false], CallMade: ["call_made", false], ExpandMore: ["keyboard_arrow_down", false],
  Mic: ["mic", true], MicOff: ["mic_off", true], VolumeUp: ["volume_up", true], Bluetooth: ["bluetooth", false],
  PhoneInTalk: ["phone_in_talk", true], Headphones: ["headphones", true], Delete: ["delete", false], Timer: ["timer", false],
  Error: ["error", false], CheckCircle: ["check_circle", true], Cancel: ["cancel", true], Visibility: ["visibility", false],
  DirectionsWalk: ["directions_walk", false], DirectionsRun: ["directions_run", false], ArrowBackIos: ["arrow_back_ios_new", false],
  Search: ["search", false], Restaurant: ["restaurant", false], Code: ["code", false], Close: ["close", false],
  Shield: ["shield", false], Smartphone: ["smartphone", false],
};
const base = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web";
const pathOf = async (sym, fill) => {
  const r = await fetch(`${base}/${sym}/materialsymbolsrounded/${sym}${fill ? "_fill1" : ""}_24px.svg`);
  if (!r.ok) throw new Error(`${sym} ${fill} ${r.status}`);
  const svg = await r.text();
  const ds = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length) throw new Error(`no path in ${sym}`);
  // Most symbols use the 960-unit viewBox (0 -960 960 960); a few older ones are plain 24-unit paths.
  const units = /viewBox="0 -960 960 960"/.test(svg) ? 960 : 24;
  return { d: ds.join(" "), units };
};
let out = `// Generated by android/scripts/symbols.mjs from Google's Material Symbols Rounded (Apache License 2.0,
// https://github.com/google/material-design-icons). Do not edit by hand; add a name to the script and run it again.
package app.helix.ui.theme

/** SVG path data, and the size of the canvas it is drawn on: 960 (viewBox 0 -960 960 960) or 24 (viewBox 0 0 24 24). */
internal class SymbolPath(val d: String, val units: Int)

internal object SymbolPaths {
`;
for (const [k, [sym, fill]] of Object.entries(names)) {
  const plain = await pathOf(sym, false);
  out += `    val ${k} = SymbolPath("${plain.d}", ${plain.units})\n`;
  if (fill) {
    const filled = await pathOf(sym, true);
    out += `    val ${k}Fill = SymbolPath("${filled.d}", ${filled.units})\n`;
  }
}
out += "}\n";
fs.writeFileSync(process.argv[2], out);
console.log("wrote", Object.keys(names).length, "symbols");
