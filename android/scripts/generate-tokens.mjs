#!/usr/bin/env node
// Regenerates android/app/src/main/java/app/helix/ui/theme/Tokens.generated.kt from design/tokens.json, the same source as
// the iPhone's Tokens.generated.swift. Usage: node android/scripts/generate-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const tokens = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));
const outPath = resolve(root, "android/app/src/main/java/app/helix/ui/theme/Tokens.generated.kt");

function argb(value) {
  const match = /^#([0-9a-f]{6})$/i.exec(value);
  if (!match) throw new Error(`Expected a #RRGGBB colour, got ${value}`);
  return `0xFF${match[1].toUpperCase()}`;
}

const colors = Object.entries(tokens.color)
  .map(([name, value]) => `    val ${name} = Color(${argb(value)})`)
  .join("\n");

const gradients = Object.entries(tokens.gradient ?? {})
  .map(([name, gradient]) => {
    const stops = gradient.stops.map((stop) => `${stop.at}f to Color(${argb(stop.color)})`).join(", ");
    const kind = gradient.direction === "vertical" ? "verticalGradient" : "horizontalGradient";
    return `    val ${name}: Brush get() = Brush.${kind}(${stops})`;
  })
  .join("\n");

const kotlin = `// Generated by android/scripts/generate-tokens.mjs from design/tokens.json. Do not edit by hand.
package app.helix.ui.theme

import androidx.compose.ui.graphics.Brush
import androidx.compose.ui.graphics.Color

object HelixColors {
${colors}
}

object HelixGradients {
${gradients}
}
`;

writeFileSync(outPath, kotlin);
console.log(`Wrote ${outPath}`);
