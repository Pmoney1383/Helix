#!/usr/bin/env node
// Regenerates ios/Helix/DesignSystem/Theme/Tokens.generated.swift from design/tokens.json.
// Usage: node ios/scripts/generate-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const tokens = JSON.parse(readFileSync(resolve(root, "design/tokens.json"), "utf8"));
const outPath = resolve(root, "ios/Helix/DesignSystem/Theme/Tokens.generated.swift");

function hex(value) {
  const match = /^#([0-9a-f]{6})$/i.exec(value);
  if (!match) throw new Error(`Expected a #RRGGBB colour, got ${value}`);
  return `0x${match[1].toUpperCase()}`;
}

const colors = Object.entries(tokens.color)
  .map(([name, value]) => `    static var ${name}: Color { Color(hex: ${hex(value)}) }`)
  .join("\n");

const gradients = Object.entries(tokens.gradient ?? {})
  .map(([name, gradient]) => {
    const [start, end] = gradient.direction === "vertical" ? [".top", ".bottom"] : [".leading", ".trailing"];
    const stops = gradient.stops
      .map((stop) => `                .init(color: Color(hex: ${hex(stop.color)}), location: ${stop.at})`)
      .join(",\n");
    return [
      `    static var ${name}: LinearGradient {`,
      `        LinearGradient(`,
      `            stops: [`,
      stops,
      `            ],`,
      `            startPoint: ${start},`,
      `            endPoint: ${end}`,
      `        )`,
      `    }`,
    ].join("\n");
  })
  .join("\n\n");

const swift = `// Generated by ios/scripts/generate-tokens.mjs from design/tokens.json. Do not edit by hand.
import SwiftUI

extension ShapeStyle where Self == Color {
${colors}
}

extension ShapeStyle where Self == LinearGradient {
${gradients}
}
`;

writeFileSync(outPath, swift);
console.log(`Wrote ${outPath}`);
